import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const moduleURL = (code) => `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`;
const compile = (path) => ts.transpileModule(readFileSync(new URL(path, import.meta.url), "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
const evidenceURL = moduleURL(compile("../lib/rightHandAudioEvidence.ts"));
const { measureAudioEvidence, isRestToken } = await import(evidenceURL);
const { parseEvaluationManifest, compareReferenceOnsets } = await import(moduleURL(compile("../lib/rightHandAudioEvaluation.ts")));
assert.equal(isRestToken("-"), true); assert.equal(isRestToken("D"), false);
assert.equal(measureAudioEvidence(new Float32Array(8000), 8000, [], .002).dynamics.consistency, null);
const sampleRate = 8000;
const samples = new Float32Array(sampleRate * 5);
const attacks = Array.from({ length: 8 }, (_, step) => ({ ms: 1200 + step * 400, step }));
for (const { ms, step } of attacks) {
  const volume = step % 2 ? .35 : .15;
  for (let i = 0; i < 650; i++) samples[Math.round(ms * sampleRate / 1000) + i] = Math.sin(i * .17) * volume * Math.exp(-i / 280);
}
const dynamics = measureAudioEvidence(samples, sampleRate, attacks, .002, [0, 1]).dynamics;
assert.ok(dynamics.deliberateAccentScore >= 95, "matching alternating accents score separately");
assert.ok(dynamics.consistency < 90, "intentional accents still vary equal-volume consistency");
const rough = Float32Array.from(samples, (value, i) => Math.abs(value) * (i % 2 ? -1 : 1));
assert.ok(measureAudioEvidence(rough, sampleRate, attacks, .002).audioIndicators.some((item) => item.kind === "roughness"));
assert.equal(measureAudioEvidence(rough, sampleRate, attacks, .8).audioIndicators.length, 0, "noisy signal cannot establish technique indicators");
const onsetResult = compareReferenceOnsets([100, 300, 500], [110, 290, 900]);
assert.equal(onsetResult.matched, 2); assert.equal(onsetResult.coveragePercent, 67); assert.equal(onsetResult.meanAbsoluteErrorMs, 10);
assert.equal(compareReferenceOnsets([100, 110], [105]).matched, 1, "one observed onset cannot cover two targets");
assert.throws(() => parseEvaluationManifest({ version: 1, samples: [{ file: "x.wav" }] }));
const valid = { file: "x.wav", device: "test microphone", instrument: "acoustic", expectedTempoBpm: 100, expectedOnsetsMs: [100, 700], consent: { granted: true, scope: "local-evaluation", source: "performer", date: "2026-10-19" } };
assert.equal(parseEvaluationManifest({ version: 1, samples: [valid] }).length, 1);
assert.throws(() => parseEvaluationManifest({ version: 1, samples: [{ ...valid, consent: { ...valid.consent, granted: false } }] }));
// Decode stub exercises the real scoring path without claiming real-recording validation.
const pulseAudio = new Float32Array(sampleRate * 4.4);
for (const ms of [300, 1200, 2000, 2800, 3600]) for (let i = 0; i < 250; i++) pulseAudio[Math.round(ms * sampleRate / 1000) + i] = Math.sin(i * .2) * .6 * Math.exp(-i / 100);
globalThis.AudioContext = class { async decodeAudioData() { return { sampleRate, duration: pulseAudio.length / sampleRate, getChannelData: () => pulseAudio }; } async close() {} };
const timingURL = moduleURL(compile("../lib/rightHandTimingReview.ts"));
const qualityURL = moduleURL(compile("../lib/rightHandRecordingQuality.ts"));
const { measureRecordingSignal } = await import(qualityURL);
assert.equal(measureRecordingSignal(Float32Array.from([0, .2, 1, .2, 0]), 8000).materiallyClipped, true, "a tiny sample is not enough to represent a useful take");
const cleanSignal = new Float32Array(8000); cleanSignal[100] = 1;
assert.equal(measureRecordingSignal(cleanSignal, 8000).materiallyClipped, false, "one isolated full-scale peak does not reject a one-second take");
cleanSignal.fill(.999, 100, 124);
assert.equal(measureRecordingSignal(cleanSignal, 8000).materiallyClipped, true, "sustained near-full-scale samples withhold reliability");
const scoringCode = compile("../lib/songRecordingAnalysis.ts").replace('"./rightHandAudioEvidence"', JSON.stringify(evidenceURL)).replace('"./rightHandTimingReview"', JSON.stringify(timingURL)).replace('"./rightHandRecordingQuality"', JSON.stringify(qualityURL));
const { analyzePracticeRecording } = await import(moduleURL(scoringCode));
const analysis = await analyzePracticeRecording(new Blob(["stub"]), { referenceBpm: 150, expectedSteps: 8, expectedFirstOnsetMs: 1200, expectedPattern: ["D", "-"], pitchScoringMode: "timing" });
assert.ok(analysis.onsetMs.every((ms) => ms >= 1165), "startup attack excluded");
assert.ok(analysis.beatTimings.every((beat) => beat.step % 2 === 0), "rests are not missed attacks");
assert.equal(analysis.expectedTimingCount, 4);
assert.ok(Math.abs(analysis.tempoDriftPercent) <= 2, "intended rests do not double the measured tempo interval");
pulseAudio.fill(1, 400, 500);
const clipped = await analyzePracticeRecording(new Blob(["stub"]), { referenceBpm: 150, expectedSteps: 8, expectedFirstOnsetMs: 1200, expectedPattern: ["D", "-"], pitchScoringMode: "timing" });
assert.equal(clipped.signalDiagnostics.materiallyClipped, true);
assert.equal(clipped.scoreReliability, "insufficient", "saturated input cannot establish reliable progress evidence");
console.log("Right-hand audio evidence: synthetic indicator/dynamics, consent, onset matching, pre-PLAY and rest checks passed. Real-recording accuracy: not evaluated.");
